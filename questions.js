  // Create a fresh 5-choice question from a topic with randomized source, stem, and 4 era-matched distractors
  synthesizeFromTopic(topic, idxNumber = 1, seedOffset = 0) {
    const all = this.topics;
    const srcIdx = (idxNumber + seedOffset + Math.floor(Math.random() * 10)) % topic.sources.length;
    const corIdx = (idxNumber + seedOffset + Math.floor(Math.random() * 10)) % topic.correct.length;
    const correctText = topic.correct[corIdx];

    // Pick 4 distractors Preferring same era or adjacent era so choices look realistic like actual 한능검!
    const sameEra = all.filter(t => t.id !== topic.id && t.era === topic.era);
    const otherEra = all.filter(t => t.id !== topic.id && t.era !== topic.era);
    const pool = [...sameEra, ...sameEra, ...otherEra];

    const usedTopicIds = new Set([topic.id]);
    const distractors = [];
    let guard = 0;
    while (distractors.length < 4 && guard < 200) {
      guard++;
      const cand = pool[Math.floor(Math.random() * pool.length)];
      if (!cand || usedTopicIds.has(cand.id)) continue;
      usedTopicIds.add(cand.id);
      const dText = cand.correct[Math.floor(Math.random() * cand.correct.length)];
      distractors.push({
        text: dText,
        isCorrect: false,
        refTitle: cand.title,
        refEra: cand.eraName
      });
    }

    const rawChoices = [
      { text: correctText, isCorrect: true, refTitle: topic.title, refEra: topic.eraName },
      ...distractors
    ];

    // Shuffle 5 choices
    for (let i = rawChoices.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [rawChoices[i], rawChoices[j]] = [rawChoices[j], rawChoices[i]];
    }

    const answerIndex = rawChoices.findIndex(c => c.isCorrect);

    // Build per-choice detailed breakdown for explanation view
    const choiceDetails = rawChoices.map((c, idx) => {
      const numCircle = ['①', '②', '③', '④', '⑤'][idx];
      if (c.isCorrect) {
        return `${numCircle} [정답] ${c.text} (${c.refTitle})`;
      } else {
        return `${numCircle} [오답 → ${c.refEra} · ${c.refTitle}] ${c.text}`;
      }
    });

    return {
      uid: `${topic.id}_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
      topicId: topic.id,
      qNum: idxNumber,
      era: topic.era,
      eraName: topic.eraName,
      title: topic.title,
      points: topic.points || 2,
      stem: topic.stem,
      source: topic.sources[srcIdx],
      choices: rawChoices.map(c => c.text),
      answer: answerIndex,
      keywords: topic.keywords || [],
      explanation: topic.exp,
      choiceDetails,
      aiGenerated: true
    };
  },

  // Generate a complete 50-question, 100-point Mock Exam matching official 한능검(심화) blueprint!
  generateFull50Exam(roundNumber = 1) {
    // Official chronological distribution across 50 questions:
    // Era 1 (선사·고조선): 4Q | Era 2 (삼국·남북국): 9Q | Era 3 (고려): 8Q
    // Era 4 (조선 전기): 7Q | Era 5 (조선 후기): 7Q | Era 6 (개항기·일제강점기): 11Q | Era 7 (현대사): 4Q = 50Q
    const quota = [
      { era: 'era1', count: 4 },
      { era: 'era2', count: 9 },
      { era: 'era3', count: 8 },
      { era: 'era4', count: 7 },
      { era: 'era5', count: 7 },
      { era: 'era6', count: 11 },
      { era: 'era7', count: 4 }
    ];

    const selectedTopics = [];
    quota.forEach(q => {
      const eraPool = this.topics.filter(t => t.era === q.era);
      const shuffled = [...eraPool].sort(() => Math.random() - 0.5);
      for (let i = 0; i < q.count; i++) {
        selectedTopics.push(shuffled[i % shuffled.length]);
      }
    });

    // Assign exact point values so total is ALWAYS 100 points (10 x 1pt + 30 x 2pt + 10 x 3pt = 100pt)
    const pointBuckets = [
      ...Array(10).fill(1),
      ...Array(30).fill(2),
      ...Array(10).fill(3)
    ].sort(() => Math.random() - 0.5);

    return selectedTopics.map((tp, idx) => {
      const q = this.synthesizeFromTopic(tp, idx + 1, roundNumber);
      q.points = pointBuckets[idx];
      return q;
    });
  },

